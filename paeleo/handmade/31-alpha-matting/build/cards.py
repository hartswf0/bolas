"""Title and end cards (3 s each, 72 frames) drawn with Pillow in the house fonts."""
import os
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__)); C = os.path.join(HERE, 'cache'); os.makedirs(C + '/cards', exist_ok=True)
FD = os.path.join(HERE, '../../../../tools/paeleo/fonts')
big = ImageFont.truetype(os.path.join(FD, 'f8.woff2'), 64)
mid = ImageFont.truetype(os.path.join(FD, 'f8.woff2'), 36)
mono = ImageFont.truetype(os.path.join(FD, 'f14.woff2'), 17)
BG = (14, 15, 26); FG = (236, 226, 210); DIM = (170, 160, 150); AMB = (240, 170, 90)


def title():
    im = Image.new('RGB', (1280, 720), BG); d = ImageDraw.Draw(im)
    d.text((110, 260), 'PAE-02 · SCION 31 · Alpha Matting', font=big, fill=FG)
    d.text((112, 350), 'Hair, lace and smoke: the threshold, handmade', font=mid, fill=AMB)
    d.text((112, 420), 'a dog at a door at dusk, composited from solved mattes of public-domain film', font=mono, fill=DIM)
    return im


END = [
    'What it is made of',
    '',
    'THE DOG  a real dog, Amateur Film New Jersey C (Home Movies, Internet Archive, public domain): 10 of its frames.',
    '         Each frame matted: SAM outline -> trimap -> solved fractional alpha -> decontaminated foreground',
    '         colour -> premultiplied RGBA. It moves by substitution of whole matted frames: a turn through its front',
    '         chosen from its own frames; backing away and coming on planted paws (one head-low frame, legs in pairs).',
    '         It was never filmed lying down: the lying dog is a RECONSTRUCTION from frame 9 (body, legs, head),',
    '         with heads from frames 5, 14, 28, 31 and a tail tuft from frame 13; its belly edge fringe synthesized.',
    'THE WOMAN AND THE DOOR LEAF  Straight Talk (NTIS 1992, public domain); her legs are drawn (reconstruction).',
    'THE HAND  Door to Heaven (1941, public domain).   CLOUDS AND HAZE  Top of the Cloud (public domain).',
    'COMPUTED  the house, porch, door light, tree line, grain, and all sound (synthesized voice; no recordings).',
    'Nothing here was generated by an image model.        Bolas · PAELEO · cohort 4',
]


def end():
    im = Image.new('RGB', (1280, 720), BG); d = ImageDraw.Draw(im)
    y = 150
    for k, line in enumerate(END):
        d.text((70, y), line, font=mid if k == 0 else mono, fill=AMB if k == 0 else (FG if not line.startswith(' ') else DIM))
        y += 50 if k == 0 else 31
    return im


def main():
    t, e = title(), end()
    for i in range(72):
        a = min(1, i / 10, (71 - i) / 10)
        Image.blend(Image.new('RGB', (1280, 720), BG), t, max(a, 0)).save(os.path.join(C, 'cards/t%03d.jpg' % i), quality=92)
        Image.blend(Image.new('RGB', (1280, 720), BG), e, max(min(1, i / 10), 0)).save(os.path.join(C, 'cards/e%03d.jpg' % i), quality=92)
    print('cards ok')


if __name__ == '__main__':
    main()
