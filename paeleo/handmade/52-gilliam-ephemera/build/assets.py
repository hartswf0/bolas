"""Writes ../assets.json: one entry per cut piece (from cache/pieces.json, as cut by cut_pieces.py) plus the entries
that are not pieces (voice, sound, painted set, fonts, not used), which are kept from the previous assets.json."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); FOLDER = os.path.dirname(HERE)
P = json.load(open(os.path.join(HERE, 'cache', 'pieces.json')))
old = json.load(open(os.path.join(FOLDER, 'assets.json')))
WHAT = {'dog_torso': 'dog torso', 'dog_head': 'dog head (profile), retouched: eye, nostril, mouth line inked',
        'dog_ear': 'dog ear, a separate card pinned at its root on the head (pricks, flicks, drops)',
        'dog_tail': 'dog tail', 'dog_front': 'turning card: the same dog facing the camera, retouched (eyes, nose inked)',
        'dog_lookback': 'the look back: a second, larger print of the profile head, retouched',
        'dog_away': 'the head turned away into the room (a lost profile): constructed collage',
        'dog_backprint': 'the back of the head, looking in: a real print (f001, the dog seen from behind), ear flaps and fur parting retouched in ink'}
for k in ('fore', 'farfore', 'hind', 'farhind'):
    WHAT['dog_' + k] = 'dog %s leg, upper card (shoulder/hip to wrist/hock)' % k
    WHAT['dog_' + k + '_lo'] = 'dog %s leg, lower card (wrist/hock to paw), toes inked' % k
assets = []
for name, r in P.items():
    src = r.get('source_print')
    copy = None
    if src:
        b = os.path.basename(src); cat = os.path.basename(os.path.dirname(os.path.dirname(src))).replace('-sam', '')
        c = 'sources/%s_%s' % (cat, b)
        copy = c if os.path.exists(os.path.join(FOLDER, c)) else None
    prov = r.get('provenance', {})
    assets.append({'id': name, 'what': WHAT.get(name, r.get('notes') or name.replace('_', ' ')),
                   'piece_file': r['file'] + ' (regenerated by build/cut_pieces.py)', 'source_print': src,
                   'source_copy_in_folder': copy, 'operation': r.get('op', ''), 'notes': r.get('notes', ''),
                   'cut_polygons_src_px': r.get('cut_polygons_src_px'), 'print_scale': r.get('scale'),
                   'tint_palette': r.get('palette'), 'pins_px': r.get('pins'), 'provenance': prov,
                   'rights': prov.get('rights', 'public_domain')})
ids = set(P)
keep = [a for a in old['assets'] if 'piece_file' not in a and a['id'] not in ids]
json.dump({'about': old['about'], 'assets': assets + keep}, open(os.path.join(FOLDER, 'assets.json'), 'w'), indent=1)
print(len(assets), 'pieces +', len(keep), 'other entries')
