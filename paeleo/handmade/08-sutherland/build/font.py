def text_strokes(s, x, y, size=12.0, track=1.5):
    """Return polylines (screen px, y down) for string s with cap height `size` px."""
    u = size / 6.0
    out = []
    cx = x
    for ch in s.upper():
        g = G.get(ch)
        if g:
            for pl in g:
                out.append([(cx + px * u, y - py * u) for px, py in pl])
        cx += (4 + 2 * track / 1.5) * u if ch != ' ' else 5 * u
    return out, cx


def text_width(s, size=12.0, track=1.5):
    return text_strokes(s, 0, 0, size, track)[1]
