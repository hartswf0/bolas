ADV = {'I': 4.2, '1': 3.6, '.': 2.2, ',': 2.2, ':': 2.2, "'": 2.2, '!': 3.4, ' ': 3.0, 'M': 5.4, 'W': 5.4}


def text_width(s, size):
    u = size / 6.0
    return sum(ADV.get(c, 5.2) * u for c in s.upper()) - 1.2 * u


def pen(d, s, x, y, size, ink=18, width=None, seed=0, anchor="l"):
    """Letter string s with its cap-top-left at (x, y); size = cap height in px.
    anchor 'l' / 'r' / 'm' horizontally. Returns (x0, x1) of the ink."""
    rnd = random.Random(seed)
    u = size / 6.0
    w = width or max(2, size * 0.13)
    tw = text_width(s, size)
    if anchor == "r":
        x -= tw
    elif anchor == "m":
        x -= tw / 2
    x0 = x
    for c in s.upper():
        dx, dy = rnd.uniform(-0.25, 0.25) * u, rnd.uniform(-0.3, 0.3) * u
        sl = rnd.uniform(-0.05, 0.08)
        sc = rnd.uniform(0.93, 1.07)
        for stroke in G.get(c, []):
            pts = [(x + dx + (px + sl * (6 - py)) * u * sc, y + dy + py * u * sc) for px, py in stroke]
            if len(pts) == 1:
                pts = pts * 2
            n = len(pts)
            for i in range(n - 1):
                (ax, ay), (bx, by) = pts[i], pts[i + 1]
                seg = max(1, int(math.hypot(bx - ax, by - ay) / 2))
                for k in range(seg + 1):
                    t = (i + k / seg) / max(1, n - 1)
                    press = 0.75 + 0.35 * math.sin(math.pi * t)
                    r = w * press / 2
                    px_, py_ = ax + (bx - ax) * k / seg, ay + (by - ay) * k / seg
                    d.ellipse([px_ - r, py_ - r, px_ + r, py_ + r], fill=ink)
        x += ADV.get(c, 5.2) * u
    return x0, x0 + tw
